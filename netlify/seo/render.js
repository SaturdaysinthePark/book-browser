// Per-page <head> and crawler text for BookJumpr's app routes. Shared by the Netlify edge function
// (netlify/edge-functions/seo.js) and the local dev server (tools/serve.mjs), so both serve the same HTML.
//
// renderPage(html, pathname, D) takes the app's index.html and the request path, and returns
//   { status, html }            — the page with its own title/description/canonical/OG tags, JSON-LD, and the
//                                 hidden crawler block (<!-- seo:start --> … <!-- seo:end -->) filled for that page;
//   { status: 301, location }   — for the legacy /book/<key> alias;
//   null                        — for the homepage (index.html already carries its own head and block).
// D is the data from netlify/seo/data.js (generated by tools/build-seo.mjs):
//   B: { key: [title, author, year, synopsis, authorSlug] }   O: { key: [[mentionedKey, note], …] }
//   I: { key: [mentioningKey, …] }                              A: { authorSlug: [name, [key, …]] }
//   G: { key: imageHash }  — books with their own preview card at /og/<key>.png (tools/render-og.mjs)
//   L: { key: [other titles] }  — alternate titles, emitted as the Book's alternateName
// Routes mirror P._routeFromHash in app.js.

export const SITE = 'https://bookjumpr.com';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const jsonLd = (o) => JSON.stringify(o).replace(/</g, '\\u003c');
const yearLabel = (y) => (!y ? '' : y < 0 ? 'c. ' + -y + ' BC' : String(y));
const known = (a) => !!a && a !== 'Anonymous';
const plural = (n, one, many) => n + ' ' + (n === 1 ? one : many);
// "A, B and C" / "A, B, C and 4 more"
const names = (list, max) => {
  const shown = list.slice(0, max), rest = list.length - shown.length;
  if (rest > 0) return shown.join(', ') + ' and ' + rest + ' more';
  return shown.length < 2 ? shown.join('') : shown.slice(0, -1).join(', ') + ' and ' + shown[shown.length - 1];
};

const ABOUT_TEXT = [
  'BookJumpr collects explicit mentions of one book inside another: a character picks a paperback off a shelf, a narrator quotes a novel they loved at fifteen, a biography lists what its subject read on a long voyage. Each mention links the two books, usually with the line where it happens, and together they make a network you can wander.',
  'It started with Kafka on the Shore: its characters kept mentioning other books, as a reference point in conversation, as something they were reading, or by name, and those titles began to leak into a reading list. Would you understand a character better if you had read the book they mention? The author chose that book on purpose.',
  'What counts as a mention: a book has to be named on the page, whether read, quoted, discussed, or dropped into conversation. Footnotes, bibliographies, and back-of-book references don’t count. Neither do allusions a critic might spot: if the text doesn’t say the title, it’s not in.',
];

function routeOf(pathname) {
  let p = String(pathname || '/').replace(/^\/+|\/+$/g, '');
  try { p = decodeURIComponent(p); } catch (e) { /* keep raw */ }
  if (!p || p === 'index.html') return { page: 'home' };
  if (p.startsWith('search/')) return { page: 'search', q: p.slice(7) };
  if (p === 'stats') return { page: 'stats' };
  if (p === 'network') return { page: 'network' };
  if (p.startsWith('network/')) return { page: 'network', focus: p.slice(8) };
  if (p === 'about') return { page: 'about' };
  if (p.startsWith('book/')) return { page: 'legacy', id: p.slice(5) };
  if (p.includes('/')) return { page: 'book', id: p };
  return { page: 'author', slug: p };
}

const link = (D, k) => `<a href="/${esc(k)}">${esc(D.B[k][0])}</a>`;
const byline = (D, k) => (known(D.B[k][1]) ? ` by ${esc(D.B[k][1])}` : '');
const bookLd = (D, k) => {
  const [t, a, y] = D.B[k], o = { '@type': 'Book', name: t, url: `${SITE}/${k}` };
  if (known(a)) o.author = { '@type': 'Person', name: a };
  if (y > 0) o.datePublished = String(y);
  if (D.L && D.L[k]) o.alternateName = D.L[k];
  return o;
};
const crumbs = (items) => ({
  '@type': 'BreadcrumbList',
  itemListElement: items.map(([name, url], i) => ({ '@type': 'ListItem', position: i + 1, name, item: url })),
});

function bookPage(D, k) {
  const [t, a, y, syn, aslug] = D.B[k], out = D.O[k] || [], inn = D.I[k] || [], yl = yearLabel(y);
  const who = known(a) ? `${t} by ${a}` : t;
  const title = out.length ? `${who}: the books it mentions | BookJumpr` : `${who}: books that mention it | BookJumpr`;
  const outNames = out.map(([m]) => D.B[m][0]), inNames = inn.map((m) => D.B[m][0]);
  let desc = out.length
    ? `${t}${yl ? ` (${yl})` : ''}${known(a) ? ` by ${a}` : ''} mentions ${plural(out.length, 'book', 'books')}: ${names(outNames, 3)}.` + (inn.length ? ` ${plural(inn.length, 'book mentions', 'books mention')} it.` : '')
    : `${who} is mentioned in ${plural(inn.length, 'book', 'books')}, including ${names(inNames, 3)}.`;
  desc += ' See each mention, with the line where it happens.';
  const body = [
    `<nav><a href="/">BookJumpr</a>${known(a) ? ` › <a href="/${esc(aslug)}">${esc(a)}</a>` : ''}</nav>`,
    `<h1>${esc(t)}</h1>`,
    `<p>${known(a) ? `by <a href="/${esc(aslug)}">${esc(a)}</a>` : 'Author unknown'}${yl ? ` · ${esc(yl)}` : ''}</p>`,
    syn ? `<p>${esc(syn)}</p>` : '',
  ];
  if (out.length) body.push(`<h2>Books mentioned in ${esc(t)} (${out.length})</h2>`, '<ul>',
    ...out.map(([m, note]) => `<li>${link(D, m)}${byline(D, m)}${note ? `: “${esc(note)}”` : ''}</li>`), '</ul>');
  if (inn.length) body.push(`<h2>Books that mention ${esc(t)} (${inn.length})</h2>`, '<ul>',
    ...inn.map((m) => `<li>${link(D, m)}${byline(D, m)}</li>`), '</ul>');
  const ld = bookLd(D, k);
  if (syn) ld.description = syn;
  if (out.length) ld.mentions = out.map(([m]) => bookLd(D, m));
  const trail = [['BookJumpr', `${SITE}/`]];
  if (known(a)) trail.push([a, `${SITE}/${aslug}`]);
  trail.push([t, `${SITE}/${k}`]);
  const image = D.G && D.G[k] ? { url: `${SITE}/og/${k}.png?v=${D.G[k]}`, alt: `${who}, and the books it mentions` } : null;
  if (image) ld.image = image.url;
  return { title, desc, canonical: `/${k}`, ogType: 'book', body, ld: [ld, crumbs(trail)], image };
}

// One author's mentions rolled up by the other author: { out, in }, each [[otherSlug, name, [[fromKey, toKey], …]], …]
// biggest first, plus the count of mentions between their own books. Mirrors P.authorAgg in app.js.
function authorAgg(D, slug) {
  const keys = D.A[slug][1], aslug = (k) => D.B[k][4] || k.split('/')[0];
  const side = (pairs) => {
    const by = new Map(); let own = 0;
    for (const [from, to, other] of pairs) {
      const s = aslug(other);
      if (s === slug) { own++; continue; }
      if (!by.has(s)) by.set(s, [s, (D.A[s] || [D.B[other][1]])[0], []]);
      by.get(s)[2].push([from, to]);
    }
    return { groups: [...by.values()].sort((x, y) => y[2].length - x[2].length || x[1].localeCompare(y[1])), own };
  };
  return {
    out: side(keys.flatMap((k) => (D.O[k] || []).filter(([m]) => D.B[m]).map(([m]) => [k, m, m]))),
    in: side(keys.flatMap((k) => (D.I[k] || []).filter((m) => D.B[m]).map((m) => [m, k, m]))),
  };
}

function authorPage(D, slug) {
  const [name, keys] = D.A[slug];
  const mentioned = keys.reduce((n, k) => n + (D.I[k] || []).length, 0);
  const agg = authorAgg(D, slug);
  const authorLink = ([s, n]) => (D.A[s] && known(n) ? `<a href="/${esc(s)}">${esc(n)}</a>` : esc(n || 'Unknown author'));
  const groupNames = (sd) => sd.groups.filter(([s, n]) => known(n)).map(([, n]) => n);
  const title = `${name}: books, and the books they mention | BookJumpr`;
  const outN = groupNames(agg.out), inN = groupNames(agg.in);
  const desc = outN.length || inN.length
    ? `${name}'s ${plural(keys.length, 'book', 'books')}` +
      (outN.length ? ` mention ${names(outN, 3)}` : '') + (outN.length && inN.length ? ', and are' : inN.length ? ' are' : '') +
      (inN.length ? ` mentioned by ${names(inN, 3)}` : '') + '. See every book-to-book link, with the quotes.'
    : `${plural(keys.length, 'book', 'books')} by ${name} on BookJumpr` + (mentioned ? `, mentioned ${plural(mentioned, 'time', 'times')} in other books` : '') +
      `: ${names(keys.map((k) => D.B[k][0]), 3)}. See what each one mentions, and what mentions it.`;
  const section = (sd, heading) => (sd.groups.length ? [
    `<h2>${esc(heading)}</h2>`, '<ul>',
    ...sd.groups.map((g) => `<li>${authorLink(g)} (${g[2].length}): ` +
      [...g[2].reduce((m, [f, t]) => m.set(f, [...(m.get(f) || []), [f, t]]), new Map())].map(([f, ps]) => `${link(D, f)} mentions ${ps.map(([, t]) => link(D, t)).join(', ')}`).join('; ') + '</li>'),
    '</ul>',
    sd.own ? `<p>Plus ${plural(sd.own, 'mention', 'mentions')} between ${esc(name)}'s own books.</p>` : '',
  ] : []);
  const body = [
    `<nav><a href="/">BookJumpr</a></nav>`,
    `<h1>${esc(name)}</h1>`,
    `<p>${plural(keys.length, 'book', 'books')} on BookJumpr${mentioned ? `, mentioned ${plural(mentioned, 'time', 'times')} in other books` : ''}.</p>`,
    `<h2>Books by ${esc(name)}</h2>`,
    '<ul>',
    ...keys.map((k) => {
      const o = (D.O[k] || []).length, i = (D.I[k] || []).length, yl = yearLabel(D.B[k][2]);
      const bits = [o ? `mentions ${plural(o, 'book', 'books')}` : '', i ? `mentioned in ${plural(i, 'book', 'books')}` : ''].filter(Boolean).join(', ');
      return `<li>${link(D, k)}${yl ? ` (${esc(yl)})` : ''}${bits ? `: ${bits}` : ''}</li>`;
    }),
    '</ul>',
    ...section(agg.out, `Authors ${name}'s books mention`),
    ...section(agg.in, `Authors who mention ${name}`),
  ].filter(Boolean);
  const url = `${SITE}/${slug}`;
  const person = { '@type': 'Person', name, url, mainEntityOfPage: url };
  const works = { '@type': 'ItemList', name: `Books by ${name}`,
    itemListElement: keys.map((k, i) => ({ '@type': 'ListItem', position: i + 1, item: bookLd(D, k) })) };
  const ld = [person, works, crumbs([['BookJumpr', `${SITE}/`], [name, url]])];
  return { title, desc, canonical: `/${slug}`, ogType: 'profile', body, ld };
}

function statsPage(D) {
  const top = Object.keys(D.I).sort((x, y) => D.I[y].length - D.I[x].length || D.B[x][0].localeCompare(D.B[y][0])).slice(0, 50);
  return {
    title: 'The most name-dropped books: which books are mentioned most in other books | BookJumpr',
    desc: `The books most often mentioned inside other books, led by ${D.B[top[0]][0]} (${D.I[top[0]].length} books), ${D.B[top[1]][0]} (${D.I[top[1]].length}) and ${D.B[top[2]][0]} (${D.I[top[2]].length}).`,
    canonical: '/stats', ogType: 'website',
    body: ['<nav><a href="/">BookJumpr</a></nav>', '<h1>The most name-dropped books</h1>', '<p>Ranked by the number of books that mention them.</p>', '<ol>',
      ...top.map((k) => `<li>${link(D, k)}${byline(D, k)}: mentioned in ${plural(D.I[k].length, 'book', 'books')}</li>`), '</ol>'],
    ld: [crumbs([['BookJumpr', `${SITE}/`], ['Stats', `${SITE}/stats`]])],
  };
}

function aboutPage() {
  return {
    title: 'About BookJumpr: how it maps the books mentioned inside other books',
    desc: 'How BookJumpr collects the books named inside other books (read, quoted, discussed, or dropped into conversation), and what counts as a mention.',
    canonical: '/about', ogType: 'website',
    body: ['<nav><a href="/">BookJumpr</a></nav>', '<h1>About BookJumpr: books talk about books</h1>', ...ABOUT_TEXT.map((p) => `<p>${esc(p)}</p>`)],
    ld: [crumbs([['BookJumpr', `${SITE}/`], ['About', `${SITE}/about`]])],
  };
}

function networkPage(D, focus) {
  const b = focus && D.B[focus];
  return {
    title: b ? `${b[0]} in the network — BookJumpr` : 'The network of books mentioned in books — BookJumpr',
    desc: 'Every book on BookJumpr as one network: each line is one book mentioning another. Pick a book and follow the lines.',
    canonical: '/network', ogType: 'website', noindex: !!focus,
    body: ['<nav><a href="/">BookJumpr</a></nav>', '<h1>The network</h1>', '<p>Every book on BookJumpr as one network: each line is one book mentioning another.</p>',
      b ? `<p>Centered on ${link(D, focus)}.</p>` : ''],
    ld: [],
  };
}

function notFound() {
  return {
    status: 404, title: 'Not found — BookJumpr', desc: 'That page isn’t in BookJumpr’s network.', canonical: null, ogType: 'website', noindex: true,
    body: ['<h1>Not found</h1>', '<p>That book or author isn’t in the network yet. <a href="/">Back to BookJumpr</a></p>'], ld: [],
  };
}

function pageFor(D, r) {
  switch (r.page) {
    case 'book': return D.B[r.id] ? bookPage(D, r.id) : notFound();
    case 'author': return D.A[r.slug] ? authorPage(D, r.slug) : notFound();
    case 'stats': return statsPage(D);
    case 'about': return aboutPage();
    case 'network': return networkPage(D, r.focus);
    case 'search': return {
      title: `“${r.q}” — Search — BookJumpr`, desc: `Books on BookJumpr matching “${r.q}”.`, canonical: null, ogType: 'website', noindex: true,
      body: ['<nav><a href="/">BookJumpr</a></nav>', `<h1>Search: “${esc(r.q)}”</h1>`], ld: [],
    };
    default: return notFound();
  }
}

// Replace a meta/link tag's content (or href) attribute, matched by its name/property/rel.
const setAttr = (html, re, value) => html.replace(re, (m, pre) => `${pre}${esc(value)}"`);

export function renderPage(html, pathname, D) {
  const r = routeOf(pathname);
  if (r.page === 'home') return null;
  if (r.page === 'legacy') return D.B[r.id] ? { status: 301, location: `/${r.id}` } : { status: 404, html: renderPage(html, '/__missing__/__missing__', D).html };
  const p = pageFor(D, r);
  const url = p.canonical ? SITE + p.canonical : null;
  let out = html.replace(/<title>[^<]*<\/title>/, `<title>${esc(p.title)}</title>`);
  out = setAttr(out, /(<meta name="description" content=")[^"]*"/, p.desc);
  out = setAttr(out, /(<meta property="og:title" content=")[^"]*"/, p.title.replace(/ \| BookJumpr$/, ''));
  out = setAttr(out, /(<meta property="og:description" content=")[^"]*"/, p.desc);
  out = setAttr(out, /(<meta property="og:type" content=")[^"]*"/, p.ogType);
  out = setAttr(out, /(<meta name="twitter:title" content=")[^"]*"/, p.title.replace(/ \| BookJumpr$/, ''));
  out = setAttr(out, /(<meta name="twitter:description" content=")[^"]*"/, p.desc);
  if (p.image) {
    out = setAttr(out, /(<meta property="og:image" content=")[^"]*"/, p.image.url);
    out = setAttr(out, /(<meta property="og:image:alt" content=")[^"]*"/, p.image.alt);
    out = setAttr(out, /(<meta name="twitter:image" content=")[^"]*"/, p.image.url);
  }
  if (url) {
    out = setAttr(out, /(<link rel="canonical" href=")[^"]*"/, url);
    out = setAttr(out, /(<meta property="og:url" content=")[^"]*"/, url);
  } else {
    out = out.replace(/<link rel="canonical" href="[^"]*">\n?/, '').replace(/<meta property="og:url" content="[^"]*">\n?/, '');
  }
  const extra = [];
  if (p.noindex) extra.push('<meta name="robots" content="noindex, follow">');
  if (p.ld.length) extra.push(`<script type="application/ld+json">${jsonLd({ '@context': 'https://schema.org', '@graph': p.ld })}</script>`);
  if (extra.length) out = out.replace('</head>', extra.join('\n') + '\n</head>');
  const block = ['<!-- seo:start — filled per page by netlify/seo/render.js; hidden once the app runs -->', '<div class="bj-seo">',
    ...p.body.filter(Boolean), '</div>', '<!-- seo:end -->'].join('\n');
  out = out.replace(/<!-- seo:start[\s\S]*?<!-- seo:end -->/, () => block);
  return { status: p.status || 200, html: out };
}
