// Builds video/film-data.js from the site's generated data (run from the repo root):
//   node video/build-data.mjs
// Everything the film shows — titles, counts, the quote, the starfield — comes from here.
import fs from 'node:fs';
import vm from 'node:vm';

const ctx = { window: {} };
vm.createContext(ctx);
for (const f of ['bookjumpr-data.js', 'bookjumpr-notes.js', 'layouts-data.js']) vm.runInContext(fs.readFileSync(f, 'utf8'), ctx);
const { NODES, MENTIONS } = ctx.window.BookJumprData;
const NOTES = {}; ctx.window.BookJumprNotes.NOTES.forEach(([i, n]) => { NOTES[i] = n; });
const L = ctx.window.BookJumprLayouts, W = L.layouts.wrap;

const GEN = { 'FICTION': '#c4682e', 'POETRY & EPICS': '#a34a9c', 'DRAMA & PLAYS': '#c33d2e', 'CRIME & MYSTERY': '#2e8156', 'SCI-FI': '#3d6fb0',
  'FANTASY': '#7b5bb5', 'HORROR': '#4a3b52', 'ADVENTURE & TRAVEL': '#c04a70', 'HISTORY': '#8a5a3a', 'BIOGRAPHY & MEMOIR': '#2f5590',
  'PHILOSOPHY': '#3f7d7d', 'PSYCHOLOGY': '#7ba03c', 'POLITICS & WORLD': '#6e6e6e', 'BUSINESS & ECONOMICS': '#8c6d24',
  'ESSAYS & JOURNALISM': '#7d4a66', 'HUMOR & COMEDY': '#d9a62b', 'FOOD & COOKING': '#a04a2a' };
const MISC = '#b3ad9f';

const ins = {}, outs = {}, deg = {};
MENTIONS.forEach(([a, b], i) => { (outs[a] = outs[a] || []).push([b, i]); (ins[b] = ins[b] || []).push([a, i]); deg[a] = (deg[a] || 0) + 1; deg[b] = (deg[b] || 0) + 1; });
const book = k => ({ id: k, t: NODES[k][0], a: NODES[k][1], y: NODES[k][2], c: GEN[NODES[k][4]] || MISC });
const top = (list, n) => [...new Set(list.map(x => x[0]))].filter(k => NODES[k]).sort((x, y) => deg[y] - deg[x]).slice(0, n).map(book);

const DQ = 'miguel-de-cervantes/don-quixote', MB = 'gustave-flaubert/madame-bovary', HR = 'harold-bloom/how-to-read-and-why';
const quoteEdge = MENTIONS.findIndex(([a, b]) => a === HR && b === MB);
if (quoteEdge < 0 || !(ins[DQ] || []).some(([a]) => a === HR)) throw new Error('How to Read and Why must mention both Don Quixote and Madame Bovary');
const quote = NOTES[quoteEdge];

// the starfield: every book on the site, at its real place on the network map, in its territory's colour
const regCol = W.regions.map(r => GEN[r.genre] || MISC);
const stars = { x: [], y: [], c: [], d: [] };
L.keys.forEach((k, i) => { stars.x.push(W.xy[2 * i]); stars.y.push(W.xy[2 * i + 1]); stars.c.push(W.reg[i]); stars.d.push(L.deg[i]); });
const idx = k => L.keys.indexOf(k);

const fan = (k, nIn, nOut) => {
  const inn = top(ins[k] || [], nIn);
  if (k === DQ && !inn.some(b => b.id === HR)) { inn.pop(); inn.splice(2, 0, book(HR)); }   // the quote's source sits in the fan
  return { ...book(k), nIn: new Set((ins[k] || []).map(x => x[0])).size, nOut: new Set((outs[k] || []).map(x => x[0])).size, inn, out: top(outs[k] || [], nOut),
    star: idx(k), links: [...new Set([...(ins[k] || []), ...(outs[k] || [])].map(x => x[0]))].map(n => [idx(n), (outs[k] || []).some(x => x[0] === n) ? 1 : 0]).filter(x => x[0] >= 0) };
};

// opening wall: the best-connected books, Don Quixote among them
const wall = Object.keys(deg).filter(k => NODES[k] && NODES[k][4]).sort((x, y) => deg[y] - deg[x]).slice(0, 60).map(book);

const out = {
  totals: { books: L.keys.length, mentions: MENTIONS.length },
  palette: regCol, misc: MISC, torus: W.guides.torus,
  dq: fan(DQ, 7, 7), mb: fan(MB, 6, 4), hr: book(HR), quote,
  wall, stars
};
fs.writeFileSync('video/film-data.js', '// generated by video/build-data.mjs — do not hand-edit\nwindow.FILM = ' + JSON.stringify(out) + ';\n');
console.log('film-data.js:', out.totals, 'quote:', quote, '| dq in', out.dq.nIn, 'out', out.dq.nOut, '| mb in', out.mb.nIn, 'out', out.mb.nOut);
console.log('dq fan in:', out.dq.inn.map(b => b.t).join(' · '));
console.log('dq fan out:', out.dq.out.map(b => b.t).join(' · '));
console.log('mb fan in:', out.mb.inn.map(b => b.t).join(' · '), '| out:', out.mb.out.map(b => b.t).join(' · '));
