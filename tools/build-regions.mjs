#!/usr/bin/env node
// build-regions.mjs — "reading neighbourhoods" for the network Explorer's entry screen.
//
// Runs the same Louvain community detection as tools/cluster-communities.mjs over the current
// mention graph (bookjumpr-data.js), keeps the genuine multi-source neighbourhoods (not the
// single-book "fan-out" bibliographies), names each one, and writes network-regions.js:
//
//   window.BookJumprRegions = { regions: [{ name, authors, size, hubKeys: [...] }] }
//
// Names default to "Around <top hub>" alongside the leading hub authors; override any region by its top hub's
// key in tools/region-names.json ({ "<hub key>": "Custom name" }). Seeded → byte-stable output.
//
// Run:  npm run bj:regions

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { loadData, mulberry32, buildLevel, louvain, modularity } from './cluster-communities.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MAX_REGIONS = 15, MIN_SIZE = 12, HUBS = 8;

const { NODES, MENTIONS } = loadData(join(ROOT, 'bookjumpr-data.js'));
const idOf = new Map(), keyOf = [];
const id = (k) => { if (!idOf.has(k)) { idOf.set(k, keyOf.length); keyOf.push(k); } return idOf.get(k); };
const edges = [], seen = new Set(), deg = new Map(), outBy = new Map();
for (const [s, t] of MENTIONS) {
  if (s === t) continue;
  deg.set(s, (deg.get(s) || 0) + 1); deg.set(t, (deg.get(t) || 0) + 1);
  const a = id(s), b = id(t), pk = a < b ? a + '-' + b : b + '-' + a;
  if (seen.has(pk)) continue;
  seen.add(pk); edges.push([a, b, 1]);
}
const base = buildLevel(keyOf.length, edges);
const rng = mulberry32(1);
let best = null;
for (let r = 0; r < 10; r++) { const c = louvain(base, 1, rng); const q = modularity(base, c, 1); if (!best || q > best.q) best = { c, q }; }
const comm = best.c;

const members = new Map();
keyOf.forEach((k, i) => { if (!members.has(comm[i])) members.set(comm[i], []); members.get(comm[i]).push(k); });
// star ratio: the top single source's internal mentions over the community's internal mentions
for (const [s, t] of MENTIONS) {
  const cs = comm[idOf.get(s)], ct = comm[idOf.get(t)];
  if (cs !== ct) continue;
  if (!outBy.has(cs)) outBy.set(cs, new Map());
  const m = outBy.get(cs); m.set(s, (m.get(s) || 0) + 1);
}

const overridesPath = join(ROOT, 'tools', 'region-names.json');
const overrides = existsSync(overridesPath) ? JSON.parse(readFileSync(overridesPath, 'utf8')) : {};

const regions = [];
for (const [c, keys] of members) {
  if (keys.length < MIN_SIZE) continue;
  const m = outBy.get(c) || new Map();
  const internal = [...m.values()].reduce((a, b) => a + b, 0) || 1;
  const star = Math.max(0, ...m.values()) / internal;
  if (star >= 0.6) continue;                     // a single book's bibliography, not a neighbourhood
  const hubs = keys.slice().sort((a, b) => (deg.get(b) || 0) - (deg.get(a) || 0) || (a < b ? -1 : 1));
  const hubTitle = NODES[hubs[0]] ? NODES[hubs[0]][0] : hubs[0];
  const authors = [];
  for (const k of hubs) { const a = NODES[k] && NODES[k][1]; if (a && a !== 'Anonymous' && authors.indexOf(a) < 0) authors.push(a); if (authors.length === 3) break; }
  const name = overrides[hubs[0]] || ('Around ' + hubTitle);
  regions.push({ name, authors, size: keys.length, hubKeys: hubs.slice(0, HUBS) });
}
regions.sort((a, b) => b.size - a.size);
const out = { regions: regions.slice(0, MAX_REGIONS) };
const js = '// GENERATED by tools/build-regions.mjs from bookjumpr-data.js — do not hand-edit.\n'
  + '// Reading neighbourhoods (Louvain, multi-source communities) for the network Explorer.\n'
  + 'window.BookJumprRegions = ' + JSON.stringify(out) + ';\n';
writeFileSync(join(ROOT, 'network-regions.js'), js);
console.log(`✓ wrote network-regions.js — ${out.regions.length} regions (Q=${best.q.toFixed(3)})`);
for (const r of out.regions) console.log(`  ${String(r.size).padStart(4)}  ${r.name}  ${r.authors.join(' · ')}`);
